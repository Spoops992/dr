# ПЕРЕВІРКА ДАТИ
# ============================================================

@app.route("/check-date", methods=["POST"])
def check_date():

    data = request.get_json(silent=True)

    if not data:

        return jsonify({
            "success": False,
            "message": "Немає даних."
        }), 400


    entered_date = str(
        data.get("date", "")
    ).strip().lower()


    # Дозволені варіанти написання дати

    allowed_dates = {
        "04.11.2004",
        "04.11.2004",
        "04/11/2004",
        "04/11/2004",
        
    }


    if entered_date in allowed_dates:

        return jsonify({
            "success": True
        })


    return jsonify({
        "success": False,
        "message": "Хммм... Схоже, дата не та 😏"
    })


